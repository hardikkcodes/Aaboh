/** The first match wins, so the specific topics come before the broad ones. */
const TOPICS: [RegExp, LucideIcon][] = [
  [/waterlog|flood|drain/i, Waves],
  [/cyclone/i, Tornado],
  [/thunder|storm|nor'wester|lightning/i, CloudLightning],
  [/\balert|warning/i, TriangleAlert],
  [/rain|drizzle|shower|precip/i, CloudRain],
  [/\buv\b|sunrise|sunset/i, Sun],
  [/satellite|layer|landsat/i, Satellite],
  [/heat|hot|temperature|feels|hotspot/i, Thermometer],
  [/humid|dew/i, Droplet],
  [/\bair\b|aqi|pm\d|pollut|station|smog/i, Wind],
  [/\bwind|gust/i, Wind],
  [/pressure/i, Gauge],
  [/visibility/i, Eye],
  [/\bcloud|overcast/i, Cloud],
  [/report|community|resident|neighbour/i, Users],
  [/route|commute/i, Route],
  [/cool|shade|tree|green/i, Trees],
  [/climate|trend|annual|year|season|change/i, TrendingUp],
  [/ground|land|place|area|map|location/i, MapPin],
  [/\bcell|grid/i, Grid3x3],
  [/insight|brief/i, Lightbulb],
  [/safety|emergenc|ready/i, ShieldCheck],
  [/plan|week|\bday/i, CalendarDays],
  [/forecast|weather|hour/i, CloudSun],
  [/account|security|profile/i, UserRound],
  [/learn|read|how|what|why/i, BookOpen],
  [/source|data|provider/i, Database],
];

export function iconFor(text: string): LucideIcon | null {
  return TOPICS.find(([pattern]) => pattern.test(text))?.[1] ?? null;
}

export const CATEGORY_ICONS: Record<string, LucideIcon> = {
  waterlogging: Waves,
  flooding: Waves,
  blocked_drainage: Droplets,
  fallen_tree: TreeDeciduous,
  road_disruption: Construction,
  power_cut: ZapOff,
  stagnant_water: Droplets,
  transport_disruption: Bus,
  environmental_hazard: TriangleAlert,
  other: CircleHelp,
};
